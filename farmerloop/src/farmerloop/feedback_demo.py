"""Offline farmer-feedback demonstration (no AWS calls).

eligible insight -> fake survey -> scheduler handoff -> SIMULATED farmer
responses, built and validated by respond.build_response under the official
outcome rules.

Part 1 follows the handoff's channel order: the first channel fails to deliver,
the record says fall back, and the next channel is tried after the handoff's
wait_hours, inside send hours.
Part 2 runs one simulated attempt per response state.

All farmer behaviour here is simulated (response keys start with "sim-").

Usage:
  .venv/bin/python -m farmerloop.feedback_demo
  .venv/bin/python -m farmerloop.feedback_demo --out    # also write JSON to out/feedback/
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, time, timedelta
from pathlib import Path

from .config import REPO_ROOT
from .demo import _pick_examples
from .generate_fake import FakeSurveyGenerator
from .outcomes import ResponseConfigError
from .schedule import build_handoff
from .simulate import simulate
from .timing import compute_window
from .validate import validate

# A delivery failure each channel can produce (all fall back to the next channel).
_UNDELIVERED_ON = {"app": "push_token_invalid", "web": "client_cannot_render",
                   "whatsapp": "wa_undelivered", "telegram": "tg_bot_blocked",
                   "voice": "voice_no_answer"}

# (channel, case) catalogue covering every response state family.
CATALOGUE = [
    ("app", "completed"),
    ("whatsapp", "negative_outcome"),
    ("telegram", "partial"),
    ("app", "sheet_closed_partway"),
    ("whatsapp", "farmer_declined"),
    ("voice", "farmer_opted_out"),
    ("app", "sheet_dismissed"),
    ("whatsapp", "free_text_instead_of_choice"),
    ("voice", "keypad_out_of_range"),
    ("voice", "speech_not_understood"),
    ("telegram", "duplicate_answer"),
    ("app", "survey_closed"),
    ("web", "survey_replaced"),
    ("telegram", "identity_mismatch"),
    ("whatsapp", "window_expired"),
    ("app", "push_not_opened"),
    ("voice", "voice_busy"),
    ("voice", "voice_call_dropped"),
]


def _next_send(at: datetime, wait_hours: int) -> datetime:
    """Next attempt after wait_hours, moved into send hours (07:00-19:00 IST)."""
    nxt = at + timedelta(hours=wait_hours)
    if nxt.time() >= time(19, 0):
        nxt = datetime.combine(nxt.date() + timedelta(days=1), time(7, 0))
    elif nxt.time() < time(7, 0):
        nxt = datetime.combine(nxt.date(), time(7, 0))
    return nxt


def _row(r: dict) -> str:
    return (f"{r['channel']:9s} {r['status']:17s} {str(r['failure_code']):28s} "
            f"{r['retry_decision']:26s} cap={str(r['counts_toward_cap']):5s} "
            f"follow_up={r['follow_up_reasons'] or '-'}  reply={(r['farmerchat_reply'] or {}).get('outcome', '-')}")


def main() -> None:
    parser = argparse.ArgumentParser(description="FarmerLoop offline feedback demo")
    parser.add_argument("--out", action="store_true", help="write records to out/feedback/")
    args = parser.parse_args()

    insight, _ = _pick_examples()
    window = compute_window(insight.created_at, insight.verification.timing,
                            insight.action_window_days)
    survey = FakeSurveyGenerator().generate(insight, window)
    created = datetime.combine(window.start - timedelta(days=1), time(23, 0))
    handoff = build_handoff(insight, survey, window, created_at=created)
    window_open = datetime.fromisoformat(handoff["send_window"]["not_before"]).replace(tzinfo=None)
    window_close = datetime.fromisoformat(handoff["send_window"]["not_after"]).replace(tzinfo=None)
    expires = datetime.fromisoformat(handoff["expires_at"]).replace(tzinfo=None)

    print("FarmerLoop feedback demo (offline, SIMULATED farmer responses)")
    print(f"insight {insight.insight_id} -> survey {survey.survey_id} ({survey.language}, "
          f"generated by: fake) -> handoff {handoff['handoff_id']}")
    print(f"send window {handoff['send_window']['not_before']} .. {handoff['send_window']['not_after']}, "
          f"expires {handoff['expires_at']}, channels "
          f"{[c['channel'] for c in handoff['channel_order']]}")

    records: list[tuple[str, dict]] = []
    try:
        # Part 1: channel fallback along the handoff's channel order.
        print("\n== Part 1: delivery with channel fallback ==")
        sent = datetime.combine(window_open.date(), time(9, 0))
        order = handoff["channel_order"]
        for idx, step in enumerate(order):
            last = idx == len(order) - 1
            case = "completed" if last else _UNDELIVERED_ON[step["channel"]]
            rec = simulate(survey, step["channel"], case, sent_at=sent, expires_at=expires,
                           delivery_attempt=1)
            records.append((f"fallback-{idx + 1}-{step['channel']}-{case}", rec))
            print(f"  {sent:%Y-%m-%d %H:%M}  {_row(rec)}")
            if rec["retry_decision"] != "fall_back_to_next_channel":
                break
            sent = _next_send(sent, step["wait_hours"])
            if sent > window_close:
                print("  next attempt would fall outside the send window; stopping")
                break

        # Part 2: one simulated attempt per response state.
        print("\n== Part 2: response states ==")
        sent = datetime.combine(window_open.date(), time(9, 0))
        for channel, case in CATALOGUE:
            rec = simulate(survey, channel, case, sent_at=sent, expires_at=expires)
            records.append((f"{channel}-{case}", rec))
            print(f"  {case:28s} {_row(rec)}")
    except ResponseConfigError as exc:
        print(f"\nFEEDBACK DEMO FAILED: {exc}", file=sys.stderr)
        raise SystemExit(1)

    invalid = [name for name, r in records if validate("response", r)]
    if invalid:
        print(f"\nFEEDBACK DEMO FAILED: schema-invalid records: {invalid}", file=sys.stderr)
        raise SystemExit(1)

    expected = (survey.survey_id, survey.farmer_id, survey.source_insight_ids, survey.language)
    broken = [name for name, r in records
              if (r["survey_id"], r["farmer_id"], r["source_insight_ids"], r["language"]) != expected]
    if broken:
        print(f"\nFEEDBACK DEMO FAILED: provenance mismatch in {broken}", file=sys.stderr)
        raise SystemExit(1)

    queue = [r for _, r in records if r["needs_follow_up"]]
    print(f"\n{len(records)} records, all valid against response.schema.json")
    print(f"follow-up queue: {len(queue)} record(s) -> "
          f"{sorted({x for r in queue for x in r['follow_up_reasons']})}")
    print(f"provenance checked: all {len(records)} records carry survey {survey.survey_id}, "
          f"farmer {survey.farmer_id}, source insight {survey.source_insight_ids}")

    if args.out:
        out_dir = REPO_ROOT / "out" / "feedback"
        out_dir.mkdir(parents=True, exist_ok=True)
        for name, r in records:
            (out_dir / f"{name}.json").write_text(
                json.dumps(r, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"wrote {len(records)} files to {out_dir}")


if __name__ == "__main__":
    main()
