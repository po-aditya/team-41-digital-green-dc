"""End-to-end Milestone-1 demonstration.

Runs the deterministic pipeline on two hand-picked insights:
  * one ELIGIBLE  -> decision -> survey -> schedule_handoff (schema-valid)
  * one INELIGIBLE -> decision -> no_survey (schema-valid) or ContractGap

By default the survey is written by the offline ContextualSurveyGenerator. Pass
--bedrock to make a single live Amazon Bedrock inference call for the eligible
insight; on any API/access error (or invalid output) we fall back to the contextual
generator and clearly label which generator produced the output.

Schema-validation failures raise DemoError so the demo exits non-zero.

Usage:
  .venv/bin/python -m farmerloop.demo
  .venv/bin/python -m farmerloop.demo --bedrock
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, time, timedelta
from typing import Any

from . import dataio
from .decide import decide
from .emit import ContractGap, emit_no_survey, now_ist
from .generate_base import SurveyGenerator, SurveyValidationError
from .generate_contextual import ContextualSurveyGenerator
from .models import Insight, Survey
from .schedule import build_handoff
from .timing import Window, compute_window
from .validate import validate


class DemoError(RuntimeError):
    """Raised when the demo produces a schema-invalid artifact."""


def _print(title: str, obj: Any) -> None:
    print(f"\n----- {title} -----")
    print(json.dumps(obj, ensure_ascii=False, indent=2))


def _assert_valid(schema: str, obj: Any) -> None:
    errors = validate(schema, obj)
    if errors:
        raise DemoError(f"{schema} failed schema: " + "; ".join(errors[:5]))
    print(f"{schema} schema: VALID")


def _pick_examples() -> tuple[Insight, Insight]:
    """Pick one truly-eligible (approved by decide() AND schedulable) and one
    ineligible insight from the golden set - not merely trusting the label."""
    eligible = ineligible = None
    for case in dataio.iter_golden():
        ins = case.insight
        if eligible is None:
            d = decide(ins)
            w = compute_window(ins.created_at, ins.verification.timing,
                               ins.action_window_days)
            if d.survey and w is not None:
                eligible = ins
        if ineligible is None and not decide(ins).survey:
            ineligible = ins
        if eligible and ineligible:
            break
    if not (eligible and ineligible):
        raise DemoError("could not find both an eligible and ineligible example")
    return eligible, ineligible


def _generate_with_fallback(
    insight: Insight, window: Window, generator: SurveyGenerator
) -> tuple[Survey, str]:
    """Generate a survey; on any error fall back to contextual templates. Returns (survey,
    generator_name_that_produced_it)."""
    if generator.name == "contextual-offline-v2":
        return generator.generate(insight, window), generator.name
    try:
        survey = generator.generate(insight, window)
        from .quality import require_quality
        require_quality(insight, survey)
        return survey, generator.name
    except SurveyValidationError as exc:
        print(f"[{generator.name}] output rejected ({exc}); falling back to contextual offline templates")
    except Exception as exc:  # boto ClientError, access/endpoint errors, etc.
        print(f"[{generator.name}] inference failed ({type(exc).__name__}: {exc}); "
              "falling back to contextual offline templates")
    return ContextualSurveyGenerator().generate(insight, window), "contextual-offline-v2 (fallback)"


def run_eligible(insight: Insight, generator: SurveyGenerator) -> None:
    print("\n================ ELIGIBLE INSIGHT ================")
    print(f"insight_id={insight.insight_id} resolution={insight.resolution_type} "
          f"lang={insight.conversation_language} timing={insight.verification.timing}")

    decision = decide(insight)
    print(f"decision: survey={decision.survey} rule={decision.rule} ({decision.notes})")

    window = compute_window(
        insight.created_at, insight.verification.timing, insight.action_window_days
    )
    if window is None:
        raise DemoError("eligible example has no schedulable window")

    survey, produced_by = _generate_with_fallback(insight, window, generator)
    survey_dump = survey.dump()
    _print(f"SURVEY (generated by: {produced_by}, language={survey.language})", survey_dump)
    _assert_valid("survey", survey_dump)

    # Simulated creation time: the day before the window opens, at 23:00 IST.
    # (Labeled simulated; a production scheduler would use a real "now".)
    sim_created = datetime.combine(window.start - timedelta(days=1), time(23, 0))
    print(f"[simulated] handoff created_at reference = {sim_created.isoformat()} IST "
          "(day before window opens)")
    handoff = build_handoff(
        insight, survey, window, created_at=now_ist(sim_created).isoformat()
    )
    _print("SCHEDULE HANDOFF", handoff)
    _assert_valid("schedule_handoff", handoff)

    # Sanity: created_at strictly before expiry.
    if handoff["created_at"] >= handoff["expires_at"]:
        raise DemoError("handoff created_at is not before expires_at")
    print(f"chronology OK: created_at {handoff['created_at']} < "
          f"expires_at {handoff['expires_at']}")


def run_ineligible(insight: Insight) -> None:
    print("\n================ INELIGIBLE INSIGHT ================")
    print(f"insight_id={insight.insight_id} resolution={insight.resolution_type} "
          f"quality={insight.quality_flag}")

    schema_ok = not validate("insight", insight.raw)
    decision = decide(insight, schema_ok=schema_ok)
    print(f"decision: survey={decision.survey} rule={decision.rule} "
          f"internal={decision.internal_reason_code} "
          f"schema_representable={decision.schema_representable}")

    result = emit_no_survey(decision)
    if isinstance(result, ContractGap):
        _print("CONTRACT GAP (not schema-representable)", {
            "insight_id": result.insight_id,
            "internal_reason_code": result.internal_reason_code,
            "rule": result.rule,
            "reason": result.reason,
        })
    else:
        dump = result.dump()
        _print("NO_SURVEY", dump)
        _assert_valid("no_survey", dump)


def main() -> None:
    parser = argparse.ArgumentParser(description="FarmerLoop Milestone-1 demo")
    parser.add_argument("--bedrock", action="store_true",
                        help="use a single live Bedrock call for the eligible survey")
    args = parser.parse_args()

    generator: SurveyGenerator = ContextualSurveyGenerator()
    if args.bedrock:
        from .generate_bedrock import BedrockSurveyGenerator
        generator = BedrockSurveyGenerator()
        print(f"[bedrock] model={generator.model_id} region={generator.region}")

    try:
        eligible, ineligible = _pick_examples()
        run_eligible(eligible, generator)
        run_ineligible(ineligible)
    except DemoError as exc:
        print(f"\nDEMO FAILED: {exc}", file=sys.stderr)
        raise SystemExit(1)
    print("\nDemo complete: all emitted artifacts are schema-valid.")


if __name__ == "__main__":
    main()
